import type { WriteResult } from '@williamthorsen/nmr-core';
import { describeError } from '@williamthorsen/toolbelt.errors';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

const mockWriteFileWithCheck = vi.hoisted(() =>
  vi.fn<(path: string, content: string, options: { isDryRun: boolean; shouldOverwrite: boolean }) => WriteResult>(),
);

vi.mock(import('@williamthorsen/nmr-core'), async (importOriginal) => {
  const actualModule = await importOriginal();
  return {
    ...actualModule,
    writeFileWithCheck: mockWriteFileWithCheck,
  };
});

const mockDeleteFileIfExists = vi.hoisted(() => vi.fn<(path: string) => void>());

vi.mock(import('../deleteFileIfExists.ts'), () => ({ deleteFileIfExists: mockDeleteFileIfExists }));

import { applyReleasePlan, type ReleasePlan } from '../releasePlan.ts';

describe(applyReleasePlan, () => {
  beforeEach(() => {
    mockWriteFileWithCheck.mockImplementation((filePath: string) => ({ filePath, outcome: 'overwritten' }));
  });

  afterEach(() => {
    mockWriteFileWithCheck.mockReset();
    mockDeleteFileIfExists.mockReset();
  });

  it('writes content files first, then the summary, then the tags file', () => {
    applyReleasePlan(makePlan());

    expect(writtenPaths()).toStrictEqual([
      'packages/core/package.json',
      'packages/core/CHANGELOG.md',
      'tmp/.release-summary',
      'tmp/.release-tags',
    ]);
  });

  it('omits the summary file when the summary is empty', () => {
    applyReleasePlan(makePlan({ summary: '' }));

    expect(writtenPaths()).not.toContain('tmp/.release-summary');
  });

  it('omits the tags file when the plan releases nothing', () => {
    applyReleasePlan(makePlan({ tags: [] }));

    expect(writtenPaths()).not.toContain('tmp/.release-tags');
  });

  it('writes one tag per line', () => {
    applyReleasePlan(makePlan({ tags: ['core-v1.0.0', 'cli-v2.1.0'] }));

    expect(mockWriteFileWithCheck).toHaveBeenCalledWith('tmp/.release-tags', 'core-v1.0.0\ncli-v2.1.0', {
      isDryRun: false,
      shouldOverwrite: true,
    });
  });

  it('returns the paths written, in order', () => {
    const returnedPaths = applyReleasePlan(makePlan());

    expect(returnedPaths).toStrictEqual([
      'packages/core/package.json',
      'packages/core/CHANGELOG.md',
      'tmp/.release-summary',
      'tmp/.release-tags',
    ]);
  });

  it('if a write fails, names the files already written', () => {
    failOn('packages/core/CHANGELOG.md');

    expect(() => applyReleasePlan(makePlan())).toThrow('1 of 4 files were written:\n  packages/core/package.json');
  });

  it('if a write fails, names the files not written', () => {
    failOn('packages/core/CHANGELOG.md');

    expect(() => applyReleasePlan(makePlan())).toThrow(
      'Not written:\n  packages/core/CHANGELOG.md\n  tmp/.release-summary\n  tmp/.release-tags',
    );
  });

  it('if a write fails, restores the release files it replaced', () => {
    failOn('packages/core/CHANGELOG.md');

    expect(() => applyReleasePlan(makePlan())).toThrow('git restore packages/core/package.json');
  });

  it('if a write fails, deletes the release files it created rather than restoring them', () => {
    failOn('packages/core/CHANGELOG.md', 'ENOSPC: no space left on device', 'created');

    expect(() => applyReleasePlan(makePlan())).toThrow('rm packages/core/package.json');
  });

  it('leaves the tags and summary files out of the recovery commands', () => {
    // They are regenerated by the next `prepare`, and are in a directory that git ignores, so `git restore` cannot restore them.
    failOn('tmp/.release-tags');

    const message = captureApplyFailure(makePlan());
    // The recovery block is the message tail, so anchoring the pattern at the end checks all of it.
    expect(message).toMatch(/git restore packages\/core\/package\.json packages\/core\/CHANGELOG\.md$/);
  });

  it('omits the recovery commands when only the handoff files were written', () => {
    failOn('tmp/.release-tags');

    expect(captureApplyFailure(makePlan({ writes: [] }))).not.toContain('Undo the written release files');
  });

  it('if a write fails, reports the underlying error', () => {
    failOn('packages/core/package.json', 'EACCES: permission denied');

    expect(() => applyReleasePlan(makePlan())).toThrow(
      'Failed to write packages/core/package.json: EACCES: permission denied',
    );
  });

  it('if the first write fails, reports that nothing was written', () => {
    failOn('packages/core/package.json');

    expect(() => applyReleasePlan(makePlan())).toThrow(
      'The release was not applied. None of its 4 files were written.',
    );
  });

  it('stops at the first failed write', () => {
    failOn('packages/core/package.json');

    expect(() => applyReleasePlan(makePlan())).toThrow('Failed to write packages/core/package.json');
    expect(writtenPaths()).toStrictEqual(['packages/core/package.json']);
  });

  describe('with removals', () => {
    const removalPath = 'packages/core/changelogs/CHANGELOG-v1.md';

    it('removes files after the content writes and before the summary and tags files', () => {
      const steps: string[] = [];
      mockWriteFileWithCheck.mockImplementation((filePath: string) => {
        steps.push(`write ${filePath}`);
        return { filePath, outcome: 'overwritten' };
      });
      mockDeleteFileIfExists.mockImplementation((filePath: string) => {
        steps.push(`remove ${filePath}`);
      });

      const appliedPaths = applyReleasePlan(makePlan({ removals: [removalPath] }));

      expect(steps).toStrictEqual([
        'write packages/core/package.json',
        'write packages/core/CHANGELOG.md',
        `remove ${removalPath}`,
        'write tmp/.release-summary',
        'write tmp/.release-tags',
      ]);
      expect(appliedPaths).toContain(removalPath);
    });

    it('if a removal fails, reports the removal and the underlying error', () => {
      mockDeleteFileIfExists.mockImplementation(() => {
        throw new Error('EACCES: permission denied');
      });

      const message = captureApplyFailure(makePlan({ removals: [removalPath] }));

      expect(message).toContain(`Failed to remove ${removalPath}: EACCES: permission denied`);
      expect(message).toContain(`Not written:\n  ${removalPath}\n  tmp/.release-summary\n  tmp/.release-tags`);
    });

    it('restores an applied removal from git when a later step fails', () => {
      failOn('tmp/.release-tags');

      const message = captureApplyFailure(makePlan({ removals: [removalPath] }));

      expect(message).toMatch(new RegExp(`git restore .*${removalPath.replaceAll('.', String.raw`\.`)}$`));
    });
  });
});

// region | Helpers
/** Builds a release plan, overriding any field of an otherwise two-file release. */
function makePlan(overrides: Partial<ReleasePlan> = {}): ReleasePlan {
  return {
    writes: [
      { path: 'packages/core/package.json', content: '{ "version": "1.0.0" }\n' },
      { path: 'packages/core/CHANGELOG.md', content: '# Changelog\n' },
    ],
    removals: [],
    tags: ['core-v1.0.0'],
    summary: 'core-v1.0.0\n- feat: Add a thing',
    formatCommand: undefined,
    targets: [],
    ...overrides,
  };
}

/**
 * Makes the write of `path` fail, leaving every other write successful.
 *
 * `successOutcome` decides whether the surviving writes replaced existing files or created them,
 * which is what the recovery commands branch on.
 */
function failOn(
  path: string,
  error = 'ENOSPC: no space left on device',
  successOutcome: WriteResult['outcome'] = 'overwritten',
): void {
  mockWriteFileWithCheck.mockImplementation((filePath: string) =>
    filePath === path ? { filePath, outcome: 'failed', error } : { filePath, outcome: successOutcome },
  );
}

/** Returns the paths passed to `writeFileWithCheck`, in call order. */
function writtenPaths(): string[] {
  return mockWriteFileWithCheck.mock.calls.map(([path]) => path);
}

/** Applies a plan expected to fail, returning the thrown message for multi-part assertions. */
function captureApplyFailure(plan: ReleasePlan): string {
  try {
    applyReleasePlan(plan);
  } catch (error) {
    return describeError(error);
  }
  throw new Error('expected applyReleasePlan to throw');
}
