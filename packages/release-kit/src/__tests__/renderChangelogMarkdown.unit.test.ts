import { describe, expect, it } from 'vitest';

import { renderChangelogFiles, renderChangelogMarkdown } from '../renderChangelogMarkdown.ts';
import type { ChangelogEntry } from '../types.ts';

/** Builds a changelog entry dated 2024-01-01 with one all-audience section containing `items`. */
function makeEntry(
  version: string,
  sectionTitle: string,
  items: Array<{ description: string; hash?: string }>,
): ChangelogEntry {
  return {
    version,
    date: '2024-01-01',
    sections: [
      {
        title: sectionTitle,
        audience: 'all',
        items,
      },
    ],
  };
}

describe(renderChangelogMarkdown, () => {
  it('emits the canonical file header at the top', () => {
    const renderedMarkdown = renderChangelogMarkdown([]);
    expect(
      renderedMarkdown.startsWith(
        '# Changelog\n\nAll notable changes to this project will be documented in this file.',
      ),
    ).toBe(true);
  });

  it('emits the canonical footer at the bottom', () => {
    const renderedMarkdown = renderChangelogMarkdown([]);
    expect(
      renderedMarkdown
        .trimEnd()
        .endsWith(
          '<!-- Generated by release-kit. Do not edit this file. Use .meta/changelog-overrides.json to override entries. -->',
        ),
    ).toBe(true);
  });

  it('terminates with a single trailing newline', () => {
    const renderedMarkdown = renderChangelogMarkdown([]);
    expect(renderedMarkdown.endsWith('\n')).toBe(true);
    expect(renderedMarkdown.endsWith('\n\n')).toBe(false);
  });

  it('renders multiple entries in the order provided', () => {
    const entries: ChangelogEntry[] = [
      makeEntry('2.0.0', 'Features', [{ description: 'Newer feature' }]),
      makeEntry('1.0.0', 'Features', [{ description: 'Older feature' }]),
    ];
    const renderedMarkdown = renderChangelogMarkdown(entries);
    const newerIndex = renderedMarkdown.indexOf('2.0.0');
    const olderIndex = renderedMarkdown.indexOf('1.0.0');
    expect(newerIndex).toBeGreaterThanOrEqual(0);
    expect(olderIndex).toBeGreaterThan(newerIndex);
  });

  it('emits H2 version + date headings for each entry', () => {
    const entries = [makeEntry('1.0.0', 'Features', [{ description: 'Add widget' }])];
    const renderedMarkdown = renderChangelogMarkdown(entries);
    expect(renderedMarkdown).toContain('## 1.0.0 — 2024-01-01');
  });

  it('emits H3 section headings under each entry', () => {
    const entries = [makeEntry('1.0.0', 'Bug fixes', [{ description: 'Fix crash' }])];
    const renderedMarkdown = renderChangelogMarkdown(entries);
    expect(renderedMarkdown).toContain('### Bug fixes');
  });

  it('renders each item as a bullet under its section', () => {
    const entries = [makeEntry('1.0.0', 'Features', [{ description: 'Add widget' }])];
    const renderedMarkdown = renderChangelogMarkdown(entries);
    expect(renderedMarkdown).toContain('- Add widget');
  });

  it("prefixes breaking items with '🚨 **Breaking:**'", () => {
    const entries: ChangelogEntry[] = [
      {
        version: '1.0.0',
        date: '2024-01-01',
        sections: [
          {
            title: 'Features',
            audience: 'all',
            items: [{ description: 'Redesign API', breaking: true }],
          },
        ],
      },
    ];
    const renderedMarkdown = renderChangelogMarkdown(entries);
    expect(renderedMarkdown).toContain('🚨 **Breaking:** Redesign API');
  });

  it('honors the provided sectionOrder', () => {
    const entries: ChangelogEntry[] = [
      {
        version: '1.0.0',
        date: '2024-01-01',
        sections: [
          { title: 'Bug fixes', audience: 'all', items: [{ description: 'Fix' }] },
          { title: 'Features', audience: 'all', items: [{ description: 'Feature' }] },
        ],
      },
    ];
    const renderedMarkdown = renderChangelogMarkdown(entries, { sectionOrder: ['Features', 'Bug fixes'] });
    const featuresIndex = renderedMarkdown.indexOf('### Features');
    const bugFixesIndex = renderedMarkdown.indexOf('### Bug fixes');
    expect(featuresIndex).toBeGreaterThanOrEqual(0);
    expect(bugFixesIndex).toBeGreaterThan(featuresIndex);
  });

  it('renders an empty entry list as just the header and footer', () => {
    const renderedMarkdown = renderChangelogMarkdown([]);
    // No version headings, no sections.
    expect(renderedMarkdown).not.toContain('##');
    expect(renderedMarkdown).toContain('# Changelog');
    expect(renderedMarkdown).toContain('Generated by release-kit');
  });

  it('omits an entry that does not render any section', () => {
    const entries: ChangelogEntry[] = [
      makeEntry('2.0.0', 'Features', [{ description: 'Feature' }]),
      { version: '1.0.0', date: '2024-01-01', sections: [] },
    ];
    const renderedMarkdown = renderChangelogMarkdown(entries);
    expect(renderedMarkdown).not.toContain('## 1.0.0');
    expect(renderedMarkdown).toContain('- Feature\n\n<!--');
  });

  describe('with preserved sections', () => {
    const entries = [
      makeEntry('3.0.0', 'Features', [{ description: 'Three' }]),
      makeEntry('1.0.0', 'Features', [{ description: 'One' }]),
    ];

    it('interleaves preserved sections verbatim by version among the rendered entries', () => {
      const renderedMarkdown = renderChangelogMarkdown(entries, {
        preservedSections: [
          { version: '0.9.0', text: '## [0.9.0] - 2023-01-01\n\n* Hand-written' },
          { version: '2.0.0', text: '## 2.0.0\n\nProse.\n\n### Notes\n\n  indented' },
          { version: '4.0.0-beta.1', text: '## v4.0.0-beta.1\n\n- Beta' },
        ],
      });

      expect(renderedMarkdown).toBe(
        [
          '# Changelog',
          '',
          'All notable changes to this project will be documented in this file.',
          '',
          '## v4.0.0-beta.1',
          '',
          '- Beta',
          '',
          '## 3.0.0 — 2024-01-01',
          '',
          '### Features',
          '',
          '- Three',
          '',
          '## 2.0.0',
          '',
          'Prose.',
          '',
          '### Notes',
          '',
          '  indented',
          '',
          '## 1.0.0 — 2024-01-01',
          '',
          '### Features',
          '',
          '- One',
          '',
          '## [0.9.0] - 2023-01-01',
          '',
          '* Hand-written',
          '',
          '<!-- Generated by release-kit. Do not edit this file. Use .meta/changelog-overrides.json to override entries. -->',
          '',
        ].join('\n'),
      );
    });

    it('renders preserved sections alone when the entry list is empty', () => {
      const renderedMarkdown = renderChangelogMarkdown([], {
        preservedSections: [
          { version: '1.0.0', text: '## 1.0.0\n\n- One' },
          { version: '1.1.0', text: '## 1.1.0\n\n- Two' },
        ],
      });

      expect(renderedMarkdown).toContain('file.\n\n## 1.1.0\n\n- Two\n\n## 1.0.0\n\n- One\n\n<!--');
    });

    it('renders the same output as an omitted option when the list is empty', () => {
      expect(renderChangelogMarkdown(entries, { preservedSections: [] })).toBe(renderChangelogMarkdown(entries));
    });
  });
});

describe(renderChangelogFiles, () => {
  const footer =
    '<!-- Generated by release-kit. Do not edit this file. Use .meta/changelog-overrides.json to override entries. -->';
  const entries = [
    makeEntry('3.1.0', 'Features', [{ description: 'Three one' }]),
    makeEntry('3.0.0', 'Features', [{ description: 'Three' }]),
    makeEntry('2.1.0', 'Features', [{ description: 'Two one' }]),
    makeEntry('1.0.0', 'Features', [{ description: 'One' }]),
  ];

  it('renders every section in the main file when keptVersionCount is omitted', () => {
    const files = renderChangelogFiles(entries);

    expect(files).toStrictEqual({ main: renderChangelogMarkdown(entries), archives: [] });
  });

  it('does not archive anything when keptVersionCount covers every section', () => {
    const files = renderChangelogFiles(entries, { keptVersionCount: 4 });

    expect(files).toStrictEqual({ main: renderChangelogMarkdown(entries), archives: [] });
  });

  it('keeps the newest sections in the main file and links to each archive below the header', () => {
    const { main } = renderChangelogFiles(entries, { keptVersionCount: 1 });

    expect(main).toBe(
      [
        '# Changelog',
        '',
        'All notable changes to this project will be documented in this file.',
        '',
        'Earlier versions: [v3](changelogs/CHANGELOG-v3.md), [v2](changelogs/CHANGELOG-v2.md), [v1](changelogs/CHANGELOG-v1.md).',
        '',
        '## 3.1.0 — 2024-01-01',
        '',
        '### Features',
        '',
        '- Three one',
        '',
        footer,
        '',
      ].join('\n'),
    );
  });

  it('archives older sections by major, newest major first, each with the header and footer', () => {
    const { archives } = renderChangelogFiles(entries, { keptVersionCount: 1 });

    expect(archives.map(({ major }) => major)).toStrictEqual([3, 2, 1]);
    expect(archives[0]?.content).toBe(
      [
        '# Changelog',
        '',
        'All notable changes to this project will be documented in this file.',
        '',
        '## 3.0.0 — 2024-01-01',
        '',
        '### Features',
        '',
        '- Three',
        '',
        footer,
        '',
      ].join('\n'),
    );
  });

  it('counts preserved sections toward keptVersionCount and archives them by major', () => {
    const files = renderChangelogFiles(entries, {
      keptVersionCount: 2,
      preservedSections: [
        { version: '3.2.0', text: '## 3.2.0\n\n- Hand-written' },
        { version: '0.9.0', text: '## 0.9.0\n\n- Early' },
      ],
    });

    expect(files.main).toContain('## 3.2.0\n\n- Hand-written');
    expect(files.main).toContain('## 3.1.0');
    expect(files.main).not.toContain('## 3.0.0');
    expect(files.archives.map(({ major }) => major)).toStrictEqual([3, 2, 1, 0]);
    expect(files.archives.at(-1)?.content).toContain('## 0.9.0\n\n- Early\n\n<!--');
  });

  it('groups a prerelease with its major', () => {
    const { archives } = renderChangelogFiles(
      [
        makeEntry('2.0.0', 'Features', [{ description: 'Two' }]),
        makeEntry('2.0.0-beta.1', 'Features', [{ description: 'Beta' }]),
      ],
      { keptVersionCount: 1 },
    );

    expect(archives).toHaveLength(1);
    expect(archives[0]?.major).toBe(2);
    expect(archives[0]?.content).toContain('## 2.0.0-beta.1');
  });
});
