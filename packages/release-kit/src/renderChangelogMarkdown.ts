import semver from 'semver';

import { describeArchivePath } from './changelogArchive.ts';
import { compareVersionsDescending } from './compareVersions.ts';
import type { VersionedMarkdownSection } from './readChangelogSections.ts';
import { renderReleaseNotesSingle } from './renderReleaseNotes.ts';
import type { ChangelogEntry } from './types.ts';

/** Top-of-file header emitted at the start of every generated `CHANGELOG.md`. */
const CHANGELOG_HEADER = `# Changelog

All notable changes to this project will be documented in this file.`;

/**
 * Bottom-of-file footer emitted after all version content. When the file is read back, `parseChangelogSections` ends
 * the last section at its opening words.
 */
const CHANGELOG_FOOTER = `<!-- Generated by release-kit. Do not edit this file. Use .meta/changelog-overrides.json to override entries. -->`;

/** Options for `renderChangelogMarkdown`. */
export interface RenderChangelogMarkdownOptions {
  /** Section titles in canonical order; passed through to `renderReleaseNotesSingle`. */
  sectionOrder?: string[];
  /**
   * Sections of the existing `CHANGELOG.md` to keep verbatim, interleaved by version among the rendered entries. A
   * section's version must not also be an entry's version.
   */
  preservedSections?: readonly VersionedMarkdownSection[];
}

/** Options for `renderChangelogFiles`. */
export interface RenderChangelogFilesOptions extends RenderChangelogMarkdownOptions {
  /** How many of the newest sections the main file keeps; every section when omitted. Must be at least 1. */
  keptVersionCount?: number;
}

/** A rendered archive file: the sections of one major version that the main file does not keep. */
export interface RenderedChangelogArchive {
  major: number;
  content: string;
}

/** The rendered `CHANGELOG.md` and its archive files, newest major first. */
export interface RenderedChangelogFiles {
  main: string;
  archives: RenderedChangelogArchive[];
}

/**
 * Renders entries and preserved sections into `CHANGELOG.md` and its per-major archive files.
 *
 * The main file keeps as many of the newest sections as `keptVersionCount` names, counting preserved sections, and
 * links to each archive file from a paragraph below its header. Each older section goes to the archive file of its
 * major version. Every file has the same header and footer.
 */
export function renderChangelogFiles(
  entries: ChangelogEntry[],
  options?: RenderChangelogFilesOptions,
): RenderedChangelogFiles {
  const sections = interleavePreservedSections(
    entries.map((entry) => ({ version: entry.version, text: renderReleaseNotesSingle(entry, options) })),
    options?.preservedSections ?? [],
  ).filter((section) => section.text.length > 0);

  const keptVersionCount = options?.keptVersionCount;
  if (keptVersionCount === undefined || sections.length <= keptVersionCount) {
    return { main: renderFile(sections), archives: [] };
  }

  const archivedGroups = groupByMajor(sections.slice(keptVersionCount));
  return {
    main: renderFile(
      sections.slice(0, keptVersionCount),
      describeArchivePointer(archivedGroups.map(({ major }) => major)),
    ),
    archives: archivedGroups.map(({ major, sections: majorSections }) => ({
      major,
      content: renderFile(majorSections),
    })),
  };
}

/**
 * Renders `ChangelogEntry[]` into a complete `CHANGELOG.md`-shaped string.
 *
 * Format:
 *   `# Changelog`
 *   blank line
 *   `All notable changes …`
 *   blank line
 *   per-entry sections (delegated to `renderReleaseNotesSingle`), with preserved sections interleaved by version
 *   blank line
 *   footer comment
 *
 * Entries are rendered in the order provided; the caller sorts (typically newest-first via
 * `compareVersionsDescending`).
 */
export function renderChangelogMarkdown(entries: ChangelogEntry[], options?: RenderChangelogMarkdownOptions): string {
  return renderChangelogFiles(entries, options).main;
}

// region | Helpers

/** Terminates a preserved section's text with a newline, as a rendered entry's text is. */
function appendTrailingNewline(section: VersionedMarkdownSection): VersionedMarkdownSection {
  return { version: section.version, text: `${section.text}\n` };
}

/** Returns the paragraph that links to each archive file, newest major first. */
function describeArchivePointer(majors: readonly number[]): string {
  const links = majors.map((major) => `[v${major}](${describeArchivePath(major)})`);
  return `Earlier versions: ${links.join(', ')}.`;
}

/** Groups sections by major version, newest major first, keeping each group's order. */
function groupByMajor(
  sections: readonly VersionedMarkdownSection[],
): Array<{ major: number; sections: VersionedMarkdownSection[] }> {
  const groups = new Map<number, VersionedMarkdownSection[]>();
  for (const section of sections) {
    const major = semver.major(section.version);
    const group = groups.get(major);
    if (group === undefined) {
      groups.set(major, [section]);
    } else {
      group.push(section);
    }
  }
  return Array.from(groups, ([major, majorSections]) => ({ major, sections: majorSections })).toSorted(
    (a, b) => b.major - a.major,
  );
}

/**
 * Returns the rendered parts, in their given order, with each preserved section placed before the first part whose
 * version is older than its own.
 */
function interleavePreservedSections(
  renderedSections: readonly VersionedMarkdownSection[],
  preservedSections: readonly VersionedMarkdownSection[],
): VersionedMarkdownSection[] {
  const sortedSections = preservedSections.toSorted((a, b) => compareVersionsDescending(a.version, b.version));
  const pendingSections = sortedSections.map(appendTrailingNewline);
  const result: VersionedMarkdownSection[] = [];
  let index = 0;
  for (const part of renderedSections) {
    let section = pendingSections[index];
    while (section !== undefined && compareVersionsDescending(section.version, part.version) < 0) {
      result.push(section);
      index++;
      section = pendingSections[index];
    }
    result.push(part);
  }
  result.push(...pendingSections.slice(index));
  return result;
}

/** Renders a file from sections: the header, an optional paragraph below it, the sections, and the footer. */
function renderFile(sections: readonly VersionedMarkdownSection[], paragraph?: string): string {
  const body = sections
    .map((section) => section.text)
    .join('\n')
    .trimEnd();

  const parts = [CHANGELOG_HEADER];
  if (paragraph !== undefined) {
    parts.push(paragraph);
  }
  if (body.length > 0) {
    parts.push(body);
  }
  parts.push(CHANGELOG_FOOTER);
  return parts.join('\n\n') + '\n';
}

