import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import { type OutputStyle, reportError, type StreamStyles } from '@williamthorsen/nmr-core';
import { describeError } from '@williamthorsen/toolbelt.errors';
import { stringify } from 'yaml';

import { CONFIG_FILE_PATH } from '../loadConfig.ts';
import { loadValidatedConfig, reportConfigProblem } from '../loadValidatedConfig.ts';
import type { RepoLabelsConfig } from '../types.ts';
import { hashPreset } from './presets.ts';
import { resolveLabels } from './resolveLabels.ts';
import { checkRetiredSyncLabelsConfig } from './retiredConfig.ts';
import type { LabelDefinition } from './types.ts';

/** Output path for the generated labels file. */
export const LABELS_OUTPUT_PATH = '.github/labels.yaml';

/**
 * Formats resolved labels as YAML under a generated header that includes the preset hashes.
 *
 * The header records `configFilePath` so that a reader of the generated file can find the config from which it came.
 */
export function formatLabelsYaml(
  labels: LabelDefinition[],
  presetHashes: Map<string, string>,
  configFilePath: string = CONFIG_FILE_PATH,
): string {
  const headerLines = ['# Generated by release-kit sync-labels — do not edit.', `# Source: ${configFilePath}`];
  const sortedPresetHashes = [...presetHashes].toSorted(([a], [b]) => a.localeCompare(b));
  for (const [name, hash] of sortedPresetHashes) {
    headerLines.push(`# ${name} preset hash: ${hash}`);
  }

  // Declare a description for every label, empty if the config does not set one.
  // `github-label-sync` reads an omitted description as "leave the label's current one alone" and an empty one as
  // "clear it", so omitting the key would leave a description on GitHub after the config stops declaring it.
  // Build each entry explicitly to fix the key order: `archived` follows `description` whether or not one was set.
  const declared = labels.map(({ archived, color, description, name }) => ({
    name,
    color,
    description: description ?? '',
    ...(archived !== undefined && { archived }),
  }));

  // `lineWidth: 0` disables line wrapping.
  const yamlBody = stringify(declared, { singleQuote: true, lineWidth: 0 });
  return headerLines.join('\n') + '\n' + yamlBody;
}

/**
 * Loads the config file and returns its `repoLabels` block.
 *
 * Reports an actionable error and returns `undefined` when the config file is missing,
 * fails to load or validate, or lacks a `repoLabels` block. Every message names the file
 * that this run read, so that `--config` never points the reader at the default path.
 */
export async function loadRepoLabelsConfig(
  stderrStyle: OutputStyle,
  configPath?: string,
): Promise<RepoLabelsConfig | undefined> {
  const result = await loadValidatedConfig(configPath);

  if (result.status === 'missing') {
    reportError(`Config file not found at ${result.configFilePath}. Run \`release-kit sync-labels init\` first.`);
    return undefined;
  }
  if (result.status === 'invalid') {
    reportConfigProblem(result.problem, stderrStyle);
    return undefined;
  }

  if (result.config.repoLabels === undefined) {
    reportError(
      `The \`repoLabels\` block is missing from ${result.configFilePath}. Run \`release-kit sync-labels init\` to seed one.`,
    );
    return undefined;
  }

  return result.config.repoLabels;
}

/** Options for the `sync-labels generate` subcommand. */
interface GenerateOptions {
  /** Compares the regenerated content against the committed file instead of writing. */
  check?: boolean;
  /** Config file to read, relative to the working directory. Defaults to `CONFIG_FILE_PATH`. */
  configPath?: string;
  styles: StreamStyles;
}

/**
 * Runs the `sync-labels generate` command and returns the process exit code.
 *
 * Writes `.github/labels.yaml` from the config's `repoLabels` block, or, with `check`, reports whether the committed
 * file is stale and writes nothing.
 *
 * The header names the config by its POSIX path relative to the working directory, the repo root, so that the file
 * does not depend on the invocation directory or on the machine on which the command ran.
 */
export async function generateCommand({ check = false, configPath, styles }: GenerateOptions): Promise<number> {
  if (checkRetiredSyncLabelsConfig(configPath)) {
    return 1;
  }

  const repoLabels = await loadRepoLabelsConfig(styles.stderr, configPath);
  if (repoLabels === undefined) {
    return 1;
  }

  let labels;
  try {
    labels = resolveLabels(repoLabels);
  } catch (error: unknown) {
    const message = describeError(error);
    reportError(`Failed to resolve labels: ${message}`);
    return 1;
  }

  const presetHashes = new Map<string, string>();
  const presetNames = repoLabels.extends ?? [];
  for (const presetName of presetNames) {
    presetHashes.set(presetName, hashPreset(presetName));
  }

  const content = formatLabelsYaml(labels, presetHashes, toRootRelativePosixPath(configPath ?? CONFIG_FILE_PATH));

  if (check) {
    return compareAgainstCommittedFile(content);
  }

  try {
    mkdirSync(path.dirname(LABELS_OUTPUT_PATH), { recursive: true });
    writeFileSync(LABELS_OUTPUT_PATH, content, 'utf8');
  } catch (error: unknown) {
    const message = describeError(error);
    reportError(`Failed to write ${LABELS_OUTPUT_PATH}: ${message}`);
    return 1;
  }

  console.info(`Generated ${LABELS_OUTPUT_PATH} with ${String(labels.length)} labels.`);
  return 0;
}

// region | Helpers

/** Compares regenerated content against the committed labels file; reports and returns an exit code. */
function compareAgainstCommittedFile(expected: string): number {
  let existing: string;
  try {
    existing = readFileSync(LABELS_OUTPUT_PATH, 'utf8');
  } catch {
    reportError(`${LABELS_OUTPUT_PATH} is missing. Run \`release-kit sync-labels generate\` and commit the result.`);
    return 1;
  }

  if (existing !== expected) {
    reportError(`${LABELS_OUTPUT_PATH} is stale. Run \`release-kit sync-labels generate\` and commit the result.`);
    return 1;
  }

  console.info(`${LABELS_OUTPUT_PATH} is up to date.`);
  return 0;
}

/** Converts a path to POSIX form relative to the working directory; a path outside it keeps its `../` segments. */
function toRootRelativePosixPath(filePath: string): string {
  return path.relative(process.cwd(), path.resolve(filePath)).split(path.sep).join('/');
}

